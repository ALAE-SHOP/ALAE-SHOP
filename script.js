let lang = localStorage.getItem('alae_language') || 'ar';
let points = 0;

window.ALAE_TEXTS = () => texts[lang];

function setLang(x) {
  lang = x;
  localStorage.setItem('alae_language', x);
  document.documentElement.lang = x;
  document.documentElement.dir = x === 'ar' ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-key]').forEach(e => {
    const t = texts[x]?.[e.dataset.key];
    if (t !== undefined) e.textContent = t;
  });
  document.querySelectorAll('.lang button').forEach(b =>
    b.classList.toggle('active', b.dataset.lang === x)
  );
  document.querySelectorAll('[data-points]').forEach(e =>
    e.textContent = Number(points || 0).toLocaleString('ar-MA')
  );
}

async function getBalance() {
  if (!window.supabaseClient || !window.ALAE_AUTH?.currentUser) {
    points = 0;
    setLang(lang);
    return 0;
  }
  const { data, error } = await window.supabaseClient.rpc('get_my_points');
  if (error) {
    console.error('get_my_points:', error);
    return points;
  }
  points = Number(data || 0);
  setLang(lang);
  return points;
}

async function claimVisit() {
  if (!window.ALAE_AUTH?.currentUser) return false;
  try {
    const { data, error } = await window.supabaseClient.rpc('claim_daily_task', {
      p_task_key: 'daily-login'
    });
    if (error) {
      console.error('claim_daily_task:', error);
      return false;
    }
    if (data?.ok) points = Number(data.points);
    else if (data?.points != null) points = Number(data.points);
    setLang(lang);
    return !!data?.ok;
  } catch (e) {
    console.warn(e);
    return false;
  }
}

async function claimTask(key) {
  if (!window.ALAE_AUTH?.currentUser) {
    alert(texts[lang].loginRequired);
    return false;
  }

  const { data, error } = await window.supabaseClient.rpc('claim_task', {
    p_task_key: key
  });

  if (error) {
    console.error(error);
    alert(error.message || texts[lang].error);
    return false;
  }

  if (!data?.ok) {
    alert(data?.message || texts[lang].alreadyDone);
    if (data?.points != null) {
      points = Number(data.points);
      setLang(lang);
    }
    return false;
  }

  points = Number(data.points);
  setLang(lang);
  return true;
}

async function claimWheelTaskBonus() {
  if (!window.ALAE_AUTH?.currentUser) return false;

  // The wheel itself is already verified by Supabase.
  // This is a separate daily bonus for completing the wheel.
  const { data, error } = await window.supabaseClient.rpc('claim_daily_task', {
    p_task_key: 'daily-wheel'
  });

  if (error) {
    console.error('daily-wheel bonus:', error);
    return false;
  }

  if (data?.points != null) {
    points = Number(data.points);
    setLang(lang);
  }

  return !!data?.ok;
}

async function beginTask(key) {
  if (!window.ALAE_AUTH?.currentUser) {
    alert(texts[lang].loginRequired);
    return null;
  }

  const { data, error } = await window.supabaseClient.rpc('begin_task', {
    p_task_key: key
  });

  if (error) {
    console.error(error);
    alert(error.message || texts[lang].error);
    return null;
  }

  if (!data?.ok) {
    alert(data?.message || texts[lang].alreadyDone);
    return null;
  }

  return data;
}

