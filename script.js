async function runVerifiedTask(btn) {
  const key = btn.dataset.id;

  // These are controlled by their own server-side events.
  if (key === 'daily-game' || key === 'daily-login' || key === 'daily-wheel') return;

  const meta = taskMeta[key];
  if (!meta) return;

  const attempt = await beginTask(key);
  if (!attempt) return;

  const modalIcon = document.getElementById('taskModalIcon');
  const countdown = document.getElementById('taskModalCountdown');
  const actions = document.getElementById('taskModalActions');

  if (!modalIcon || !countdown || !actions) return;

  modalIcon.textContent = meta.icon;
  actions.innerHTML = '';
  document.getElementById('taskModalTitle').textContent = texts[lang].modalComplete;
  document.getElementById('taskModalText').textContent = texts[lang].waiting;
  modal(true);

  let remaining = Number(meta.seconds);
  countdown.textContent = `${remaining} ${texts[lang].seconds}`;

  // Special tasks are verified by their server-side requirement + timer.
  // External tasks require an actual click on the destination/share action.
  let opened = key.startsWith('special-');

  if (key === 'daily-share') {
    const share = async () => {
      try {
        if (navigator.share) {
          await navigator.share({
            title: 'ALAE_SHOP.1',
            text: 'ALAE_SHOP.1',
            url: location.origin
          });
          opened = true;
        } else {
          await navigator.clipboard.writeText(location.origin);
          opened = true;
          alert(texts[lang].done);
        }
      } catch (_) {}
    };

    const b = document.createElement('button');
    b.type = 'button';
    b.className = 'btn primary';
    b.textContent = texts[lang].startExternal;
    b.onclick = share;
    actions.appendChild(b);
  } else if (meta.url) {
    const a = document.createElement('a');
    a.className = 'btn primary';
    a.href = meta.url;
    a.target = '_blank';
    a.rel = 'noopener noreferrer';
    a.textContent = texts[lang].startExternal;
    a.addEventListener('click', () => { opened = true; }, { once: true });
    actions.appendChild(a);
  } else {
    const b = document.createElement('button');
    b.type = 'button';
    b.className = 'btn primary';
    b.textContent = texts[lang].startExternal;
    b.disabled = true;
    actions.appendChild(b);
  }

  await new Promise(resolve => {
    const timer = setInterval(() => {
      remaining--;
      countdown.textContent = `${Math.max(0, remaining)} ${texts[lang].seconds}`;
      if (remaining <= 0) {
        clearInterval(timer);
        resolve();
      }
    }, 1000);
  });

  const claim = document.createElement('button');
  claim.type = 'button';
  claim.className = 'btn primary';
  claim.textContent = texts[lang].claim;
  claim.disabled = !opened;

  claim.onclick = async () => {
    claim.disabled = true;
    const ok = await claimTask(key);

    if (ok) {
      btn.disabled = true;
      btn.textContent = texts[lang].done;
      document.getElementById('taskModalText').textContent = texts[lang].taskClaimed;
      countdown.textContent = '✓';
      setTimeout(() => modal(false), 900);
    } else {
      claim.disabled = false;
    }
  };

  actions.appendChild(claim);
}

async function spinWheel() {
  if (!window.ALAE_AUTH?.currentUser) {
    alert(texts[lang].loginRequired);
    return;
  }

  const wheel = document.querySelector('#wheel');
  const spin = document.querySelector('.spin-btn');
  const result = document.querySelector('.result');

  if (!wheel || !spin) return;

  spin.disabled = true;

  const { data, error } = await window.supabaseClient.rpc('spin_wheel');

  if (error || !data?.ok) {
    spin.disabled = false;
    if (result) result.textContent = data?.message || error?.message || texts[lang].error;
    if (data?.next_spin_at_ms) updateWheelCooldown(Number(data.next_spin_at_ms));
    return;
  }

  const index = Number(data.segment_index);
  const rotation = 360 * 7 + (360 - index * 45);
  wheel.style.transform = `rotate(${rotation}deg)`;

  setTimeout(async () => {
    const win = data.reward;

    if (result) {
      result.textContent = win === 'retry'
        ? texts[lang].retry
        : `${texts[lang].won} ${win} ${texts[lang].pointsWord}!`;
    }

    points = Number(data.points);
    setLang(lang);

    // Separate daily +5 bonus, only once per day.
    if (win !== 'retry') {
      await claimWheelTaskBonus();
    }

    spin.disabled = false;
    updateWheelCooldown(Number(data.next_spin_at_ms || 0));
  }, 4850);
}

function updateWheelCooldown(next) {
  const el = document.querySelector('[data-wheel-cooldown]');
  if (!el) return;

  const left = Math.max(0, Number(next || 0) - Date.now());

  if (left <= 0) {
    el.textContent = texts[lang].spinAvailable;
    return;
  }

  let sec = Math.ceil(left / 1000);
  const h = Math.floor(sec / 3600);
  const m = Math.floor((sec % 3600) / 60);
  const s = sec % 60;

  el.textContent =
    `${texts[lang].spinAgain} ${String(h).padStart(2, '0')} : ${String(m).padStart(2, '0')} : ${String(s).padStart(2, '0')}`;

  setTimeout(() => updateWheelCooldown(next), 1000);
}

async function initWheel() {
  if (!window.ALAE_AUTH?.currentUser) return;

  const { data, error } = await window.supabaseClient.rpc('get_wheel_status');

  if (error) {
    console.error('get_wheel_status:', error);
    return;
  }

  if (data) updateWheelCooldown(Number(data.next_spin_at_ms || 0));
}

async function setupRewardedAd() {
  const ad = document.querySelector('[data-id="daily-game"]');
  if (!ad || !window.ALAE_AUTH?.currentUser) return;

  let waiting = false;
  let timer = null;

  // Attach the rewarded event listener BEFORE waiting for the event.
  const attach = () => {
    if (!window.googletag?.pubads) return false;

    try {
      window.googletag.pubads().addEventListener('rewardedSlotGranted', async () => {
        if (!waiting) return;

        waiting = false;
        clearTimeout(timer);

        const ok = await claimTask('daily-game');
        ad.disabled = ok;
        ad.textContent = ok ? texts[lang].done : '🎬 مشاهدة الإعلان';
      });
      return true;
    } catch (e) {
      console.error('rewardedSlotGranted listener:', e);
      return false;
    }
  };

  const listenerAttached = attach();

  ad.addEventListener('click', async () => {
    if (!listenerAttached) {
      alert('إعلان المكافأة غير مهيأ في الموقع.');
      return;
    }

    ad.disabled = true;
    ad.textContent = '⏳ ...';

    // Start the server-side attempt before waiting for the real rewarded event.
    // Without this, claim_task() correctly refuses the ad because no attempt exists.
    const attempt = await beginTask('daily-game');
    if (!attempt) {
      ad.disabled = false;
      ad.textContent = '🎬 مشاهدة الإعلان';
      return;
    }

    waiting = true;
    window.ALAE_AD_WAITING = true;

    timer = setTimeout(() => {
      if (waiting) {
        waiting = false;
        window.ALAE_AD_WAITING = false;
        ad.disabled = false;
        ad.textContent = '🎬 مشاهدة الإعلان';
      }
    }, 30000);
  });
}

async function initTasks() {
  await getBalance();

  // Visit-site reward is server-side and can only be credited once/day.
  await claimVisit();
  await getBalance();

  const { data, error } = await window.supabaseClient.rpc('get_daily_task_status');

  if (error) {
    console.error('get_daily_task_status:', error);
    return;
  }

  const done = new Set(
    (data || []).filter(x => x.completed).map(x => x.task_key)
  );

  document.querySelectorAll('.task-btn').forEach(btn => {
    const key = btn.dataset.id;

    if (done.has(key)) {
      btn.disabled = true;
      btn.textContent = texts[lang].done;
      return;
    }

    btn.addEventListener('click', () => runVerifiedTask(btn));
  });

  await setupRewardedAd();
}

async function initSiteVisit() {
  if (!window.ALAE_AUTH?.currentUser) return;
  await claimVisit();
  await getBalance();
}

document.addEventListener('DOMContentLoaded', async () => {
  document.querySelectorAll('.lang button').forEach(b =>
    b.addEventListener('click', () => setLang(b.dataset.lang))
  );

  setLang(lang);

  await (window.ALAE_AUTH_READY || Promise.resolve());

  // Award the visit bonus once per day on any page of the site.
  await initSiteVisit();

  if (document.querySelector('[data-points]')) await getBalance();
  if (document.querySelector('.task-btn')) await initTasks();

  if (document.querySelector('#wheel')) {
    document.querySelector('.spin-btn')?.addEventListener('click', spinWheel);
    await initWheel();
  }

  document.getElementById('taskModalClose')?.addEventListener('click', () => modal(false));
});
